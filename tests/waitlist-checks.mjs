import assert from "node:assert/strict"
import { randomUUID } from "node:crypto"
export async function waitlistChecks({ db, client, signIn, password, accounts, admin, anonymous, family, post, createEvent, mails, setMailFailure }) {
  const a = await family("wait-a@example.com"), b = await family("wait-b@example.com"), reception = client(), kine = client()
  for (const [request, account] of [[reception, accounts[0]], [kine, accounts[2]]]) await signIn(request, "equipo", { email: account.email, password })
  const path = "/api/familias/lista-espera", full = await createEvent(admin, "Lista FIFO", 1)
  const payload = (event, name, extra = {}) => ({ id: randomUUID(), eventoId: event.id, nombreBebe: name, fechaNacimiento: "2026-01-01", nombreApoderado: "Apoderado espera", aceptaAsignacion: true, ...extra })
  async function ok(request, url, body, expected = 200, method = "POST") {
    const response = await request(url, { ...post(body), method }), value = await response.json()
    assert.equal(response.status, expected, `${url}: ${JSON.stringify(value)}`); return value
  }
  const register = async (who, event, name, extra) => (await ok(who.request, "/api/familias/inscripciones", payload(event, name, extra), 201)).inscripcion
  const join = async (who, event, name, extra) => (await ok(who.request, path, payload(event, name, extra))).solicitud
  const cancel = (who, event, id) => ok(who.request, `/api/inscripciones/${id}/cancelacion`, { eventoId: event.id, motivo: "La familia libera su reserva" })
  const own = async who => (await (await who.request(path)).json()).solicitudes
  const state = async id => (await db.query('SELECT estado,"inscripcionId",orden FROM "ListaEspera" WHERE id=$1', [id])).rows[0]
  const counters = async event => (await db.query('SELECT inscritos,"ultimoNumero" FROM "Evento" WHERE id=$1', [event.id])).rows[0]
  const holder = await register(a, full, "Titular inicial")
  assert((await (await anonymous("/api/eventos/disponibles")).json()).eventos.find(e => e.id === full.id).listaEspera)
  for (const request of [anonymous, admin]) assert.equal((await request(path, post(payload(full, "Sin acceso")))).status, 401)
  assert.equal((await kine(`/api/lista-espera/${full.id}`)).status, 403)
  assert.equal((await a.request(`/api/lista-espera/${full.id}`)).status, 401)
  assert.equal((await a.request(path, post(payload(full, "Sin consentimiento", { aceptaAsignacion: false })))).status, 400)
  const empty = await createEvent(admin, "Con cupos", 2), closed = await createEvent(admin, "Cerrado", 1, false)
  for (const event of [empty, closed]) assert.equal((await a.request(path, post(payload(event, "No debe esperar")))).status, 409)
  assert.equal((await a.request(path, post(payload(full, "Inscrito", { bebeId: holder.bebe.id })))).status, 409)
  const firstPayload = payload(full, "Primero en espera", { orden: -999, createdAt: "2000-01-01" })
  const first = (await ok(b.request, path, firstPayload)).solicitud
  assert.equal(first.orden, 1); assert.equal(first.posicion, 1); assert.equal(first.numero, null)
  assert.equal((await ok(b.request, path, firstPayload)).solicitud.id, first.id)
  assert.equal((await join(b, full, "Primero en espera")).id, first.id)
  const second = await join(a, full, "Segundo en espera"), third = await join(b, full, "Tercero en espera")
  assert.equal(second.orden, 2); assert.equal(third.posicion, 3)
  assert.deepEqual(await counters(full), { inscritos: 1, ultimoNumero: 1 })
  assert.equal((await db.query('SELECT count(*)::int n FROM "Inscripcion" WHERE id=$1', [first.id])).rows[0].n, 0)
  assert(!(await own(a)).some(row => row.id === first.id))
  assert.equal((await a.request(`/api/familias/lista-espera/${first.id}/retirar`, post({}))).status, 404)
  const staff = await (await reception(`/api/lista-espera/${full.id}`)).json()
  assert.equal(staff.pendientes, 3); assert.deepEqual(staff.solicitudes.map(row => row.orden), [1, 2, 3])
  const result = await cancel(a, full, holder.id)
  assert(!("promociones" in result)); assert(!JSON.stringify(result).includes(first.id))
  assert.equal((await state(first.id)).estado, "ASIGNADA"); assert.equal((await state(second.id)).estado, "PENDIENTE")
  assert.deepEqual(await counters(full), { inscritos: 1, ultimoNumero: 2 })
  const confirmed = (await (await b.request("/api/familias/inscripciones")).json()).inscripciones.find(row => row.id === first.id)
  assert.equal(confirmed.numero, 2); assert.equal(confirmed.origen, "PREVIA")
  assert.equal((await b.request(`/api/familias/inscripciones/${first.id}/qr`)).status, 200)
  assert(mails.some(mail => JSON.stringify(mail).includes("Tu cupo se confirmó desde la lista de espera")))
  assert.equal((await b.request(`/api/familias/lista-espera/${first.id}/retirar`, post({}))).status, 409)
  await ok(a.request, `/api/familias/lista-espera/${second.id}/retirar`, {})
  assert.equal((await state(second.id)).estado, "RETIRADA")
  assert.equal((await own(b)).find(row => row.id === third.id).posicion, 1)
  const rejoin = await join(a, full, "Segundo en espera")
  assert.equal(rejoin.orden, 4); assert.notEqual(rejoin.id, second.id)
  assert.equal((await db.query('SELECT count(*)::int n FROM "Paciente" WHERE nombre=$1', ["Segundo en espera"])).rows[0].n, 1)
  await ok(admin, `/api/eventos/${full.id}/inscripciones`, { abiertas: false }, 200, "PATCH")
  setMailFailure(true)
  await cancel(b, full, first.id)
  setMailFailure(false)
  assert.equal((await state(third.id)).estado, "ASIGNADA", "Cerrar el formulario no borra solicitudes aceptadas")
  assert.equal((await db.query('SELECT estado FROM "CorreoInscripcion" WHERE "inscripcionId"=$1', [third.id])).rows[0].estado, "FALLIDO")
  await db.query('UPDATE "CorreoInscripcion" SET "disponibleAt"=now()-interval \'1 second\' WHERE "inscripcionId"=$1', [third.id])
  assert.equal((await b.request(`/api/familias/inscripciones/${third.id}/correo`, post({}))).status, 200)
  // Capacity edits must process old requests and return the post-assignment count.
  let latest = (await (await admin("/api/eventos")).json()).eventos.find(row => row.id === full.id)
  const expanded = await ok(admin, `/api/eventos/${full.id}`, { ...latest, cupos: 2 }, 200, "PATCH")
  assert.equal(expanded.evento.inscritos, 2); assert.equal((await state(rejoin.id)).estado, "ASIGNADA")
  assert.deepEqual(await counters(full), { inscritos: 2, ultimoNumero: 4 })
  assert.equal((await a.request(path, post(payload(full, "No reactivar", { bebeId: holder.bebe.id })))).status, 409)
  console.log("OK lista de espera: consentimiento, permisos, FIFO, reintentos, datos reutilizados, retirada, cupos/correo/QR y ampliación automática.")

  // Recovery gap: an otherwise free slot remains reserved for the pending head.
  const today = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Santiago", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date())
  const recovery = await createEvent(admin, "Recuperación FIFO", 1)
  await db.query('UPDATE "Evento" SET fecha=$2::date WHERE id=$1', [recovery.id, today])
  const occupied = await register(a, recovery, "Reserva de recuperación")
  const head = await join(b, recovery, "Cabeza recuperable"), tail = await join(a, recovery, "Cola recuperable")
  await db.query('UPDATE "Evento" SET cupos=2 WHERE id=$1', [recovery.id])
  assert.equal((await a.request("/api/familias/inscripciones", post(payload(recovery, "No adelantar")))).status, 409)
  assert.equal((await reception("/api/recepcion/presencial", post(payload(recovery, "Tampoco presencial")))).status, 409)
  await ok(reception, `/api/lista-espera/${recovery.id}`, {})
  assert.equal((await state(head.id)).estado, "ASIGNADA")
  assert.equal((await (await b.request("/api/familias/inscripciones")).json()).inscripciones.find(row => row.id === head.id).origen, "PRESENCIAL")
  // Force a conversion failure: cancellation and reassignment roll back together.
  await db.exec(`CREATE FUNCTION wait_fail() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.id='${tail.id}'::uuid THEN RAISE EXCEPTION 'wait fixture'; END IF; RETURN NEW; END $$; CREATE TRIGGER wait_failure BEFORE INSERT ON "Inscripcion" FOR EACH ROW EXECUTE FUNCTION wait_fail();`)
  const failed = await a.request(`/api/inscripciones/${occupied.id}/cancelacion`, post({ eventoId: recovery.id, motivo: "Cancelación con fallo simulado" }))
  assert.equal(failed.status, 503)
  assert.equal((await db.query('SELECT count(*)::int n FROM "CancelacionInscripcion" WHERE "inscripcionId"=$1', [occupied.id])).rows[0].n, 0)
  assert.equal((await state(tail.id)).estado, "PENDIENTE"); assert.deepEqual(await counters(recovery), { inscritos: 2, ultimoNumero: 2 })
  await db.exec('DROP TRIGGER wait_failure ON "Inscripcion"; DROP FUNCTION wait_fail();')
  const concurrent = await Promise.all([cancel(a, recovery, occupied.id), cancel(b, recovery, head.id)])
  assert.equal(concurrent.length, 2); assert.equal((await state(tail.id)).estado, "ASIGNADA")
  assert.deepEqual(await counters(recovery), { inscritos: 1, ultimoNumero: 3 })
  assert.equal((await db.query('SELECT count(*)::int n FROM "Inscripcion" WHERE id=$1', [tail.id])).rows[0].n, 1)
  // Inactive owners are recorded as ineligible, never silently reassigned.
  const invalid = await createEvent(admin, "Elegibilidad", 1), initial = await register(a, invalid, "Titular elegibilidad")
  const ineligible = await join(b, invalid, "Cuenta inactiva"), eligible = await join(a, invalid, "Cuenta vigente")
  const owner = b.user.id.replace(/^familia:/, "")
  await db.query('UPDATE "Apoderado" SET activo=false WHERE id=$1', [owner])
  await cancel(a, invalid, initial.id)
  await db.query('UPDATE "Apoderado" SET activo=true WHERE id=$1', [owner])
  assert.equal((await state(ineligible.id)).estado, "NO_ELEGIBLE"); assert.equal((await state(eligible.id)).estado, "ASIGNADA")
  assert.equal((await (await a.request(path + "?pagina=0")).json()).error.length > 0, true)
  console.log("OK recuperación FIFO: sin adelantamientos web/presenciales, rollback íntegro, concurrencia sin sobrecupos y elegibilidad auditada.")
}
